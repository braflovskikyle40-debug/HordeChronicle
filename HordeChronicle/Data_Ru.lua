-- Кириллица: строчная → заглавная (string.upper работает только с латиницей)
local LOWER = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
local UPPER = "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ"
local CHAR = "[%z\1-\127\194-\244][\128-\191]*"
local UP = {}
do
  local lo, hi = {}, {}
  for ch in LOWER:gmatch(CHAR) do lo[#lo + 1] = ch end
  for ch in UPPER:gmatch(CHAR) do hi[#hi + 1] = ch end
  for i = 1, #lo do UP[lo[i]] = hi[i] end
end

function D.ucfirst(s)
  if not s or s == "" then return s end
  local first = s:match("^" .. CHAR)
  return (UP[first] or first:upper()) .. s:sub(#first + 1)
end

return D
